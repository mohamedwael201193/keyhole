//! Closed, original NEAR action-receipt graph. Missing evidence is UNKNOWN.
use base64::{engine::general_purpose::STANDARD as B64, Engine};
use serde_json::Value;
use std::collections::{BTreeMap, BTreeSet};
#[derive(Debug, PartialEq)]
pub enum Terminal {
    Success { bytes: Vec<u8>, executor: String },
    Failure,
}
pub fn has_failure(v: &Value) -> bool {
    v["receipts_outcome"].as_array().is_some_and(|rs| {
        rs.iter()
            .any(|r| r["outcome"]["status"].get("Failure").is_some())
    })
}
pub fn terminal(
    v: &Value,
    hash: &str,
    signer: &str,
    receiver: &str,
    allowed: Option<&[&str]>,
) -> Option<Terminal> {
    let v = v.get("result").unwrap_or(v);
    if v["final_execution_status"] != "FINAL"
        || v["transaction"]["hash"] != hash
        || v["transaction"]["signer_id"] != signer
        || v["transaction"]["receiver_id"] != receiver
    {
        return None;
    }
    let root = &v["transaction_outcome"];
    if root["id"] != hash || root["outcome"]["executor_id"] != signer {
        return None;
    }
    let rs = v["receipts_outcome"].as_array()?;
    if rs.len() > 256 {
        return None;
    }
    let mut nodes = BTreeMap::new();
    nodes.insert(hash, root);
    for r in rs {
        let id = r["id"].as_str()?;
        if id.is_empty() || nodes.insert(id, r).is_some() {
            return None;
        }
    }
    let mut parents = BTreeMap::new();
    let mut edges = BTreeMap::new();
    for (id, r) in &nodes {
        let o = &r["outcome"];
        let executor = o["executor_id"].as_str()?;
        if !crate::is_valid_account_id(executor)
            || (*id != hash && allowed.is_some_and(|a| !a.contains(&executor)))
        {
            return None;
        }
        let st = o["status"].as_object()?;
        if st.len() != 1
            || !(st.contains_key("SuccessReceiptId")
                || st.contains_key("SuccessValue")
                || st.contains_key("Failure"))
        {
            return None;
        }
        if let Some(x) = st.get("SuccessValue") {
            B64.decode(x.as_str()?).ok()?;
        }
        let children = o["receipt_ids"].as_array()?;
        let mut child_ids = BTreeSet::new();
        for x in children {
            let x = x.as_str()?;
            if !nodes.contains_key(x)
                || x == hash
                || !child_ids.insert(x)
                || parents.insert(x, *id).is_some()
            {
                return None;
            }
        }
        if let Some(x) = st.get("SuccessReceiptId") {
            let x = x.as_str()?;
            if !nodes.contains_key(x) || x == *id {
                return None;
            }
            child_ids.insert(x);
        }
        edges.insert(*id, child_ids);
    }
    // Every outcome must be generated by one original reachable action, not merely
    // referenced by a forged SuccessReceiptId. No orphan/data ambiguity is accepted.
    if nodes
        .keys()
        .any(|id| *id != hash && !parents.contains_key(id))
    {
        return None;
    }
    fn walk<'a>(
        id: &'a str,
        e: &BTreeMap<&'a str, BTreeSet<&'a str>>,
        active: &mut BTreeSet<&'a str>,
        seen: &mut BTreeSet<&'a str>,
    ) -> Option<()> {
        if active.contains(id) {
            return None;
        }
        if seen.contains(id) {
            return Some(());
        }
        active.insert(id);
        for x in e.get(id)? {
            walk(x, e, active, seen)?;
        }
        active.remove(id);
        seen.insert(id);
        Some(())
    }
    let mut seen = BTreeSet::new();
    walk(hash, &edges, &mut BTreeSet::new(), &mut seen)?;
    if seen.len() != nodes.len() {
        return None;
    }
    // The first returned action belongs to the actual transaction receiver.
    if let Some(first) = root["outcome"]["status"]["SuccessReceiptId"].as_str() {
        if nodes[first]["outcome"]["executor_id"] != receiver {
            return None;
        }
    }
    let mut current = hash;
    loop {
        let o = &nodes[current]["outcome"];
        let st = &o["status"];
        if let Some(next) = st["SuccessReceiptId"].as_str() {
            current = next;
            continue;
        }
        if st != &v["status"] {
            return None;
        }
        return if st.get("Failure").is_some() {
            Some(Terminal::Failure)
        } else {
            Some(Terminal::Success {
                bytes: B64.decode(st["SuccessValue"].as_str()?).ok()?,
                executor: o["executor_id"].as_str()?.into(),
            })
        };
    }
}
#[cfg(test)]
pub(crate) fn fixture(hash: &str, signer: &str, receiver: &str, value: &str) -> Value {
    use serde_json::json;
    json!({"final_execution_status":"FINAL","transaction":{"hash":hash,"signer_id":signer,"receiver_id":receiver},"status":{"SuccessValue":B64.encode(value)},"transaction_outcome":{"id":hash,"outcome":{"executor_id":signer,"receipt_ids":["call"],"status":{"SuccessReceiptId":"call"}}},"receipts_outcome":[{"id":"call","outcome":{"executor_id":receiver,"receipt_ids":[],"status":{"SuccessValue":B64.encode(value)}}}]})
}
#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;
    fn check(v: &Value) -> Option<Terminal> {
        terminal(
            v,
            "tx",
            "minter.near",
            "keys.near",
            Some(&["minter.near", "keys.near", "outlayer.near"]),
        )
    }
    #[test]
    fn closed_original_success_and_failure() {
        let mut v = fixture("tx", "minter.near", "keys.near", "true");
        assert!(matches!(check(&v), Some(Terminal::Success { .. })));
        v["receipts_outcome"][0]["outcome"]["status"] = json!({"Failure":{"ActionError":"failed"}});
        v["status"] = v["receipts_outcome"][0]["outcome"]["status"].clone();
        assert_eq!(check(&v), Some(Terminal::Failure));
    }
    #[test]
    fn rejects_missing_root_or_missing_failure_lineage() {
        let mut v = fixture("tx", "minter.near", "keys.near", "true");
        v["transaction_outcome"] = Value::Null;
        assert_eq!(check(&v), None);
        v["status"] = json!({"Failure":{}});
        v["receipts_outcome"] = Value::Null;
        assert_eq!(check(&v), None);
    }
    #[test]
    fn rejects_orphan_duplicate_dangling_cycle_pending_and_wrong_executor() {
        let good = fixture("tx", "minter.near", "keys.near", "true");
        let mut v = good.clone();
        v["receipts_outcome"].as_array_mut().unwrap().push(json!({"id":"orphan","outcome":{"executor_id":"keys.near","receipt_ids":[],"status":{"SuccessValue":""}}}));
        assert_eq!(check(&v), None);
        let mut v = good.clone();
        let r = v["receipts_outcome"][0].clone();
        v["receipts_outcome"].as_array_mut().unwrap().push(r);
        assert_eq!(check(&v), None);
        for status in [
            json!({"SuccessReceiptId":"absent"}),
            json!({"SuccessReceiptId":"call"}),
            json!({"Unknown":null}),
        ] {
            let mut v = good.clone();
            v["receipts_outcome"][0]["outcome"]["status"] = status;
            assert_eq!(check(&v), None);
        }
        for executor in ["other.near", "outlayer.near"] {
            let mut v = good.clone();
            v["receipts_outcome"][0]["outcome"]["executor_id"] = json!(executor);
            assert_eq!(check(&v), None);
        }
    }
    #[test]
    fn rejects_contradictory_root_result() {
        let mut v = fixture("tx", "minter.near", "keys.near", "false");
        v["status"] = json!({"SuccessValue":B64.encode("true")});
        assert_eq!(check(&v), None);
    }
}
